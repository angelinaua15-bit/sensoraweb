const DICTS: Record<Locale, Dict> = { en, es }

/** Simple {{var}}-free `{var}` interpolation — no ICU plural rules needed for this dictionary's content. */
export function translate(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  const template = DICTS[locale][key] ?? DICTS.en[key] ?? key
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_, name) => (vars[name] !== undefined ? String(vars[name]) : `{${name}}`))
}

